  /**
   * Dịch một khoá, thay các tham số dạng {tên} nếu có.
   * @param {string} key khoá trong từ điển
   * @param {object} [params] ví dụ { n: 3, v: 'roll' }
   * @returns {string}
   */
  function t(key, params) {
    var table = DICT[current] || DICT.vi;
    var text = table[key];
    if (text === undefined) text = DICT.vi[key];      // lùi về tiếng Việt
    if (text === undefined) return key;               // để lộ khoá thiếu khi phát triển
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, function (match, name) {
      return params[name] !== undefined ? params[name] : match;
    });
  }

  /** Định dạng số theo đúng quy ước của ngôn ngữ đang chọn (1.234 hay 1,234). */
  function num(value) {
    return Number(value).toLocaleString(current === 'vi' ? 'vi-VN' : 'en-US');
  }

  /** Định dạng mốc thời gian theo ngôn ngữ đang chọn. */
  function locale() {
    return current === 'vi' ? 'vi-VN' : 'en-US';
  }

  function getLang() { return current; }

  /** Đổi ngôn ngữ và báo cho mọi thành phần đã đăng ký vẽ lại. */
  function setLang(lang) {
    if (!DICT[lang] || lang === current) return;
    current = lang;
    document.documentElement.setAttribute('lang', lang);
    try { localStorage.setItem(STORE_KEY, lang); } catch (e) { /* chế độ riêng tư */ }
    listeners.forEach(function (fn) { fn(lang); });
  }

  function onChange(fn) { listeners.push(fn); }

  /**
   * Công cụ kiểm tra từ điển — chạy trong Console của trình duyệt:
   *      DLU.i18n.audit()
   * Trả về danh sách khoá có ở ngôn ngữ này nhưng thiếu ở ngôn ngữ kia.
   * Hữu ích mỗi khi thêm câu chữ mới để không sót bản dịch.
   */
  function audit() {
    var viKeys = Object.keys(DICT.vi);
    var enKeys = Object.keys(DICT.en);
    return {
      total: viKeys.length,
      missingInEn: viKeys.filter(function (k) { return !(k in DICT.en); }),
      missingInVi: enKeys.filter(function (k) { return !(k in DICT.vi); })
    };
  }

  /**
   * Đọc ngôn ngữ đã lưu từ lần truy cập trước.
   * Đây là đồ án tiếng Việt nên mặc định là 'vi', không đoán theo trình duyệt —
   * người chấm bài mở lần đầu phải thấy ngay tiếng Việt.
   */
  function init() {
    var saved = null;
    try { saved = localStorage.getItem(STORE_KEY); } catch (e) { /* bỏ qua */ }
    current = DICT[saved] ? saved : 'vi';
    document.documentElement.setAttribute('lang', current);
  }

  DLU.i18n = {
    t: t, num: num, locale: locale,
    getLang: getLang, setLang: setLang, onChange: onChange, init: init,
    audit: audit, LANGS: ['vi', 'en']
  };
